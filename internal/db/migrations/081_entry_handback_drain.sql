-- 081 — a surplus machine is emptied before it is handed back (plan 42 П9.17).
--
-- Until now the surplus handback killed the machine's relays on the spot and
-- every session on them was cut. Now the hub first takes the relays out of the
-- pool the way a rollout does (status 'draining': holders refetch, a client
-- moves its session before letting go), and hands the machine back on a later
-- pass, once nobody is left on it or the drain deadline passed, and only in the
-- last minutes of the hour the hoster has already been paid for.
--
-- handback_since is that state: when the drain for a handback began. NULL on
-- every machine that is not leaving. Cleared when the pool needs the machine
-- back after all (the relays are restored); meaningless once retired.
ALTER TABLE entry_boxes ADD COLUMN handback_since timestamptz;
