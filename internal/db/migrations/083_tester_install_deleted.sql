-- Удалённый тестер: установщик, который больше не тестер (мёртвый аккаунт,
-- старый тестовый вход). Строка остаётся тумбстоуном, а не пропадает:
--   * алиас и install_id не выдаются заново (номер тестера означает одного
--     человека навсегда);
--   * счётчики продукта (люди, версии, «на связи») по-прежнему знают, что этот
--     install — не человек, и не считают его ни тестером, ни юзером.
-- Видно только deleted_at: с него установщик пропадает из списка тестеров,
-- из резолва по имени, а его чанки и команды удаляются.
ALTER TABLE support_install_aliases ADD COLUMN IF NOT EXISTS deleted_at timestamptz;

-- Счётчик «на связи» и фильтры метрик читают только непустые строки.
CREATE INDEX IF NOT EXISTS support_install_aliases_deleted_idx
    ON support_install_aliases (deleted_at)
    WHERE deleted_at IS NOT NULL;
