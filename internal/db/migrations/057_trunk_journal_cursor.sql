-- Докуда hub прочитал журнал входа (internal/cascadewatch collect). Раньше
-- курсор жил только в памяти, и hub после перезапуска читал журнал заново с
-- последней минутной строки входа: события пула между ней и перезапуском
-- ложились в trunk_runs вторым рядом (10.11 19:20 UTC, выкатка c545181), и
-- сводка trunk считала смерти членов дважды. Теперь курсор пишется в той же
-- транзакции, что и строки, которые он закрывает.
CREATE TABLE trunk_journal_cursor (
    entry_box text PRIMARY KEY,
    read_to timestamptz NOT NULL
);

